// The env image's recipe (design §8.2 step 1), written for the code-runner's image contract
// (verdikta-arbiter code-runner/README.md, "What the env image (P3a) must provide").
//
// Two stages. `setup`, FROM the foundry base pinned in @verdikta/common: the listed commit's
// objects (fetched on the host) become /repo/.git, the commit and its submodules are checked out,
// and the maker's `commands.setup` runs in /repo as root with the build's network. Its HOME is a
// build-only directory that is thrown away, and XDG_DATA_HOME points under /opt/verdikta/tools,
// so tools it installs the usual way (forge's solc downloads, say) land outside $HOME and /tmp.
// The final stage is FROM the same pinned base and runs nothing (no RUN, so no network): it copies
// the tools (owned by root) and /repo (owned by uid 10001, the sandbox user, with its objects and
// installed dependencies), and declares no VOLUME, USER, ENTRYPOINT or CMD of its own. /bin/sh and
// everything else outside those two directories are the pinned base's bytes.
//
// The maker's setup text never becomes Dockerfile text: it is setup.sh in the build context.
import fs from 'node:fs';
import path from 'node:path';

import { codeReview } from './common.js';
import { PLATFORMS } from './config.js';

export const IMAGE_LAYOUT = Object.freeze({
  repo: '/repo',
  tools: '/opt/verdikta/tools',
  xdgData: '/opt/verdikta/tools/share',
  buildDir: '/verdikta-build',
  buildHome: '/verdikta-build/home',
  sandboxUid: 10001,
});

/** The pinned base image's PATH (ghcr.io/foundry-rs/foundry v1.8.5); the tools come after it. */
const BASE_PATH = '/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin';
const CLASS_PLATFORM = codeReview.CLASS_HARD_LIMITS.platform;
const COMMIT = /^[0-9a-f]{40}(?:[0-9a-f]{24})?$/;
const SEMVER = /^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$/;

/**
 * The base image references. The class build (setup on linux/amd64, no extra platform) uses the
 * pinned linux/amd64 manifest; a dev build for other platforms uses the pinned multi-platform
 * index, which resolves to that same manifest for linux/amd64.
 * @param {{ setup: string, extra: string[] }} platforms
 * @returns {{ setup: string, final: string, attested: string }}
 */
export function baseImageRefs({ setup, extra = [] }) {
  for (const p of [setup, ...extra]) if (!PLATFORMS.includes(p)) throw new TypeError(`unknown platform ${p}`);
  const pin = codeReview.BASE_IMAGE_PINS.foundry;
  if (setup === CLASS_PLATFORM && extra.length === 0) {
    const ref = `${pin.repository}@${pin.digest}`;
    return { setup: ref, final: ref, attested: pin.reference };
  }
  const ref = `${pin.repository}@${pin.indexDigest}`;
  return { setup: ref, final: ref, attested: `${pin.repository}:${pin.version}@${pin.indexDigest}` };
}

/**
 * @param {object} o
 * @param {string} o.baseCommit
 * @param {boolean} o.hasSetup - whether setup.sh is in the context
 * @param {{ setup: string, final: string }} o.refs - baseImageRefs()
 * @param {{ setup: string }} o.platforms
 * @param {string} o.builderVersion
 */
export function renderDockerfile({ baseCommit, hasSetup, refs, platforms, builderVersion }) {
  if (typeof baseCommit !== 'string' || !COMMIT.test(baseCommit)) throw new TypeError('baseCommit must be a full lowercase commit id');
  if (typeof builderVersion !== 'string' || !SEMVER.test(builderVersion)) throw new TypeError('the builder version must be semver');
  if (!PLATFORMS.includes(platforms.setup)) throw new TypeError(`unknown platform ${platforms.setup}`);
  const L = IMAGE_LAYOUT;
  const toolsPath = `${BASE_PATH}:${L.tools}/bin`;
  return [
    `# Generated by the Verdikta environment builder ${builderVersion} for commit ${baseCommit}.`,
    `FROM --platform=${platforms.setup} ${refs.setup} AS setup`,
    'USER root',
    `ENV HOME=${L.buildHome} XDG_DATA_HOME=${L.xdgData} VERDIKTA_TOOLS=${L.tools} PATH=${toolsPath}`,
    `COPY repo.git ${L.repo}/.git`,
    ...(hasSetup ? [`COPY setup.sh ${L.buildDir}/setup.sh`] : []),
    `RUN mkdir -p ${L.buildHome} ${L.xdgData} ${L.tools}/bin \\`,
    ` && git -C ${L.repo} checkout --quiet --force --detach ${baseCommit} \\`,
    // A submodule git cannot fetch is left as the setup leaves it, as the code-runner leaves one it has no objects for.
    ` && if [ -f ${L.repo}/.gitmodules ]; then git -C ${L.repo} submodule update --init --recursive --quiet || echo "verdikta-builder: git submodule update failed; the submodules are left to the setup" >&2; fi`,
    ...(hasSetup ? [`RUN cd ${L.repo} && /bin/sh -e ${L.buildDir}/setup.sh`] : []),
    `RUN chmod -R a+rX,go-w ${L.repo} ${L.tools}`,
    '',
    `FROM ${refs.final}`,
    `COPY --from=setup ${L.tools} ${L.tools}`,
    `COPY --from=setup --chown=${L.sandboxUid}:${L.sandboxUid} ${L.repo} ${L.repo}`,
    `ENV XDG_DATA_HOME=${L.xdgData} VERDIKTA_TOOLS=${L.tools} PATH=${toolsPath}`,
    `LABEL io.verdikta.listing.base-commit="${baseCommit}" io.verdikta.builder.version="${builderVersion}"`,
    '',
  ].join('\n');
}

/**
 * Writes the build context: the fetched objects as repo.git, the maker's setup as setup.sh, and
 * the Dockerfile.
 * @returns {{ dockerfile: string, refs: object }}
 */
export function writeBuildContext({ dir, gitDir, setup, baseCommit, platforms, builderVersion }) {
  fs.mkdirSync(dir, { recursive: true });
  const target = path.join(dir, 'repo.git');
  try {
    fs.renameSync(gitDir, target);
  } catch {
    fs.cpSync(gitDir, target, { recursive: true });
  }
  const hasSetup = typeof setup === 'string' && setup.length > 0;
  if (hasSetup) fs.writeFileSync(path.join(dir, 'setup.sh'), `${setup}\n`, { mode: 0o644 });
  const refs = baseImageRefs(platforms);
  const dockerfile = renderDockerfile({ baseCommit, hasSetup, refs, platforms, builderVersion });
  fs.writeFileSync(path.join(dir, 'Dockerfile'), dockerfile);
  return { dockerfile, refs };
}
